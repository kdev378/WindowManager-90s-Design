/* 1 回の描画・計測で扱う UCS-2 の上限。タイトルは WM_TITLE_MAX バイトなので
 * グリフ数はこれを超えない。 */
#define FONT_MAX_GLYPHS   256

/* PolyText16 のテキストアイテムあたりの上限。255 はフォント切替の標識に
 * 予約されているため 254 (§4.5.4.1)。 */
